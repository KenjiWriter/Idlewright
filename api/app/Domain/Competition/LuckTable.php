<?php

declare(strict_types=1);

namespace App\Domain\Competition;

use InvalidArgumentException;
use JsonException;

/**
 * The luck of a run: a number drawn from a normal distribution, in parts per million of the lap time, so that the better car does not always win. The table is data
 * (content/tables/luck-ppm.json): the quantiles of the standard normal distribution at 1000 evenly spaced chances, in ppm. A roll from 0 to 999 999 (the
 * `Rng` of the game) picks the entry, and the width of the luck (sigma) of the game multiplies it, so the game code never computes a logarithm or a root while it
 * plays and every platform gets the same numbers.
 */
final readonly class LuckTable
{
    public const SIZE = 1_000;

    /** @param list<int> $quantilePpm index = roll div 1000, the standard normal quantile times a million */
    private function __construct(private array $quantilePpm)
    {
        if (count($quantilePpm) !== self::SIZE) {
            throw new InvalidArgumentException('The luck table needs '.self::SIZE.' entries, got '.count($quantilePpm).'.');
        }
    }

    public static function fromJson(string $json): self
    {
        try {
            $data = json_decode($json, true, 512, JSON_THROW_ON_ERROR);
        } catch (JsonException $exception) {
            throw new InvalidArgumentException('The luck table is not valid JSON: '.$exception->getMessage(), 0, $exception);
        }

        $values = $data['quantile_ppm'] ?? null;

        if (! is_array($values) || array_filter($values, static fn (mixed $value): bool => ! is_int($value)) !== []) {
            throw new InvalidArgumentException('The luck table needs a list of integers in quantile_ppm.');
        }

        return new self(array_values($values));
    }

    public static function fromFile(string $path): self
    {
        $json = @file_get_contents($path);

        if ($json === false) {
            throw new InvalidArgumentException("Cannot read the luck table at {$path}.");
        }

        return self::fromJson($json);
    }

    /**
     * The luck of a roll, in ppm of the lap time: the quantile of the roll times the width of the luck. Negative is a quicker run.
     *
     * @param  int  $roll  from 0 to 999 999
     * @param  int  $sigmaPpm  the width of the luck, as a part of the lap time (20 000 is 2%)
     */
    public function luckPpm(int $roll, int $sigmaPpm): int
    {
        $quantile = $this->quantilePpm[max(0, min(self::SIZE - 1, intdiv($roll, 1_000)))];
        $product = $quantile * $sigmaPpm;

        // Rounds half away from zero, like every multiplier of the game.
        return $product >= 0 ? intdiv($product + 500_000, 1_000_000) : -intdiv(-$product + 500_000, 1_000_000);
    }

    /**
     * Computes the table with floating point numbers (the inverse of the normal distribution, Acklam's rational approximation, relative error about 1e-9). This runs
     * only to create the data file and to check that it is not stale; the game reads the file.
     *
     * @return list<int>
     */
    public static function compute(): array
    {
        $values = [];

        for ($i = 0; $i < self::SIZE; $i++) {
            $values[] = (int) round(self::normalQuantile(($i + 0.5) / self::SIZE) * 1_000_000);
        }

        return $values;
    }

    /** The JSON stored in content/tables/luck-ppm.json. */
    public static function computedJson(): string
    {
        return json_encode([
            'description' => 'The luck of a run: quantiles of the standard normal distribution at 1000 evenly spaced chances, in ppm (index = roll div 1000). Multiplied by the width of the luck of the game (sigma, in ppm of the lap time). Generated by php artisan content:luck-table.',
            'size' => self::SIZE,
            'quantile_ppm' => self::compute(),
        ], JSON_PRETTY_PRINT | JSON_THROW_ON_ERROR)."\n";
    }

    private static function normalQuantile(float $p): float
    {
        $a = [-3.969683028665376e+01, 2.209460984245205e+02, -2.759285104469687e+02, 1.383577518672690e+02, -3.066479806614716e+01, 2.506628277459239e+00];
        $b = [-5.447609879822406e+01, 1.615858368580409e+02, -1.556989798598866e+02, 6.680131188771972e+01, -1.328068155288572e+01];
        $c = [-7.784894002430293e-03, -3.223964580411365e-01, -2.400758277161838e+00, -2.549732539343734e+00, 4.374664141464968e+00, 2.938163982698783e+00];
        $d = [7.784695709041462e-03, 3.224671290700398e-01, 2.445134137142996e+00, 3.754408661907416e+00];
        $low = 0.02425;

        if ($p < $low) {
            $q = sqrt(-2 * log($p));

            return ((((($c[0] * $q + $c[1]) * $q + $c[2]) * $q + $c[3]) * $q + $c[4]) * $q + $c[5]) / (((($d[0] * $q + $d[1]) * $q + $d[2]) * $q + $d[3]) * $q + 1);
        }

        if ($p > 1 - $low) {
            $q = sqrt(-2 * log(1 - $p));

            return -((((($c[0] * $q + $c[1]) * $q + $c[2]) * $q + $c[3]) * $q + $c[4]) * $q + $c[5]) / (((($d[0] * $q + $d[1]) * $q + $d[2]) * $q + $d[3]) * $q + 1);
        }

        $q = $p - 0.5;
        $r = $q * $q;

        return ((((($a[0] * $r + $a[1]) * $r + $a[2]) * $r + $a[3]) * $r + $a[4]) * $r + $a[5]) * $q / ((((($b[0] * $r + $b[1]) * $r + $b[2]) * $r + $b[3]) * $r + $b[4]) * $r + 1);
    }
}
